import {test} from 'node:test';
import assert from 'node:assert/strict';
const base='http://127.0.0.1:10000';
const phone='+380671234567';
const authpass='test-admin-password-123456';
const dateAdd=(d,n)=>{const dt=new Date(d+'T00:00:00Z');dt.setUTCDate(dt.getUTCDate()+n);return dt.toISOString().slice(0,10)};
async function req(path,options){const r=await fetch(base+path,options);const body=await r.json();return {status:r.status,body,headers:r.headers}}
const json=(method,body,session)=>({method,headers:{'Content-Type':'application/json',...(session?{Cookie:session}:{})},body:JSON.stringify(body)});
test('Two simultaneous students cannot reserve the same lesson',async()=>{
 const info=await req('/api/info');assert.equal(info.status,200);assert.equal(info.body.timezone,'Europe/Kyiv');assert.equal(info.body.duration,60);
 const date=dateAdd(info.body.today,2),slots=await req('/api/slots?date='+date+'&durationMinutes=180');
 assert.equal(slots.status,200);assert.equal(slots.body.slots[0].time,'06:00');assert.equal(slots.body.slots.at(-1).time,'20:00');
 const selected=slots.body.slots.find(s=>s.status==='free');assert.ok(selected);
 const ends=await req('/api/ends?date='+date+'&start='+selected.time);
 assert.equal(ends.status,200);
 assert.equal(ends.body.start,'06:00');
 assert.ok(ends.body.ends.some(x=>x.time==='07:00'&&x.durationMinutes===60));
 assert.ok(ends.body.ends.some(x=>x.time==='08:00'&&x.durationMinutes===120));
 assert.ok(ends.body.ends.some(x=>x.time==='21:00'&&x.durationMinutes===900));

 const submission={date,time:selected.time,durationMinutes:180,name:'Тестовий учень',phone,note:'Лише автоматичний тест',website:'',policyAccepted:true};
 const responses=await Promise.all([req('/api/book',json('POST',submission)),req('/api/book',json('POST',submission))]);
 assert.deepEqual(responses.map(r=>r.status).sort(),[201,409]);
 assert.equal(responses.find(r=>r.status===201).body.duration,180);
 const endsAfter=await req('/api/ends?date='+date+'&start=06:00');
 assert.equal(endsAfter.status,200);
 assert.equal(endsAfter.body.ends.length,0,'cannot select finish inside booked 3-hour lesson');
 const endsFromNine=await req('/api/ends?date='+date+'&start=09:00');
 assert.ok(endsFromNine.body.ends.some(x=>x.time==='10:00'));
 const reserved=await req('/api/slots?date='+date+'&durationMinutes=60');
 for(const h of ['06:00','07:00','08:00'])assert.equal(reserved.body.slots.find(x=>x.time===h).status,'busy');
 assert.equal(reserved.body.slots.find(x=>x.time==='09:00').status,'free');
 const shorter=await req('/api/slots?date='+date+'&durationMinutes=30');assert.equal(shorter.body.slots.find(x=>x.time==='08:00').status,'busy');
 const overlapAttempt=await req('/api/book',json('POST',{...submission,time:'08:00',durationMinutes:60}));assert.equal(overlapAttempt.status,409);
 const publicDump=JSON.stringify(reserved.body);assert.ok(!publicDump.includes(phone));assert.ok(!publicDump.includes(submission.name));
 const bad=await req('/api/admin/state');assert.equal(bad.status,401);
 const wrong=await req('/api/admin/login',json('POST',{password:'incorrect password'}));assert.equal(wrong.status,401);
 const login=await req('/api/admin/login',json('POST',{password:authpass}));assert.equal(login.status,200);
 const cookie=login.headers.get('set-cookie').split(';')[0];
 const admin=await req('/api/admin/state',{headers:{Cookie:cookie}});assert.equal(admin.status,200);
 const booking=admin.body.bookings.find(b=>b.day===date&&b.start_min===360&&b.status==='confirmed');assert.ok(booking);assert.equal(booking.student_name,submission.name);assert.equal(booking.phone,phone);assert.equal(booking.duration_min,180);
 const cancel=await req('/api/admin/cancel',json('POST',{id:booking.id},cookie));assert.equal(cancel.status,200);
 const after=await req('/api/slots?date='+date);for(const h of ['06:00','07:00','08:00'])assert.equal(after.body.slots.find(x=>x.time===h).status,'free');
 const off=await req('/api/admin/override',json('PUT',{date,closed:true,start:360,end:1260},cookie));assert.equal(off.status,200);
 const closed=await req('/api/slots?date='+date);assert.equal(closed.body.slots.length,0);
 const back=await req('/api/admin/override',json('DELETE',{date},cookie));assert.equal(back.status,200);
 const open=await req('/api/slots?date='+date);assert.equal(open.body.slots.length,15);
 const duration900=await req('/api/slots?date='+date+'&durationMinutes=900');assert.equal(duration900.body.slots.filter(x=>x.status==='free').length,1);
 const blocked=await req('/api/admin/block',json('PUT',{date,time:selected.time,blocked:true},cookie));assert.equal(blocked.status,200);
 const check=await req('/api/slots?date='+date);assert.equal(check.body.slots.find(x=>x.time===selected.time).status,'blocked');
 const overlappingBlock=await req('/api/slots?date='+date+'&durationMinutes=180');assert.equal(overlappingBlock.body.slots.find(x=>x.time==='06:00').status,'blocked');
 const blockedAttempt=await req('/api/book',json('POST',submission));assert.equal(blockedAttempt.status,409);
 const unblocked=await req('/api/admin/block',json('PUT',{date,time:selected.time,blocked:false},cookie));assert.equal(unblocked.status,200);
 const weekly=await req('/api/admin/weekly',json('PUT',{duration:60,days:[1,2,3,4,5,6,7].map(dow=>({dow,enabled:true,start:360,end:1260}))},cookie));assert.equal(weekly.status,200);
 const exportCsv=await fetch(base+'/api/admin/export',{headers:{Cookie:cookie}});assert.equal(exportCsv.status,200);assert.match(exportCsv.headers.get('content-type'),/text\/csv/);
});
